H2("8.1", "关键问题讨论")
B("本模块设计中最值得记录的问题是联系方式的访问权限边界：既要防止非相关用户获取发布者的个人联系方式造成打扰，又要保证发布者本人能够随时核对和在编辑场景下正确回显自己填写的信息。最初采用“发布者也不能查看自己联系方式”的过严规则，在集成测试阶段暴露出编辑功能的数据丢失问题，修正后改为“发布者本人不受状态限制查看、非发布者按书籍是否仍可交易判断”，这一经验也提示：权限规则不能仅从“谁需要被限制”单方面设计，还需要结合该数据在同一模块内被哪些功能复用来通盘考虑。")
B("状态机设计上权衡了简单性与真实场景的匹配度：完全不设中间状态（只有在售/已下架）虽然实现简单，但无法表达“已有人在谈但还没完全确定”这一常见的二手书交易过程；引入“已预定”状态后，既保留了对其他买家的提示作用，又不强制锁定导致发布者在买家放弃后无法恢复在售，取消预定的存在使状态机保持可逆、非终态之间可以双向流转，仅在确定成交或不再出售时才进入不可逆的终态。")
B("并发处理上，书籍状态变更使用行锁保证顺序执行，而收藏操作选择依赖数据库唯一约束而非行锁：收藏属于低冲突、高频次的操作，使用唯一约束加 IntegrityError 捕获既能保证并发安全，又避免了为高频操作引入额外的锁等待开销，是根据实际读写特征选择一致性保证机制的例子。")

